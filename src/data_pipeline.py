"""FORGE data pipeline — reproducible cleaning + dedup + splitting.

Stages (each records decisions in the manifest):
  1. language/size/empty/binary/generated/minified pre-filters
  2. license filter (permissive-only for clean release; configurable)
  3. quality filters (unparseable, low alpha-frac, boilerplate)
  4. secrets scan (regex; flags, does not silently drop)
  5. exact dedup (sha256 of raw bytes)
  6. near-dup (inverted-index candidate generation + exact Jaccard verify)
  7. decontamination hooks (see decontam.py)
  8. deterministic hash-based train/val/test split (no dup can cross splits)
  9. manifest (JSONL): source, hash, language, license, decisions, reasons

Design rules:
- Pure stdlib. No torch, no numpy. Runs on VM, Kaggle CPU, Termux.
- Deterministic: stream order in, sorted iteration everywhere, hash-based
  split. Same input + same config => byte-identical manifest.
- Configurable thresholds; unusual-but-legitimate code is preserved by
  default (filters target empty/binary/generated/minified only).
"""
from __future__ import annotations

import ast
import hashlib
import json
import re
import time
from collections import defaultdict
from dataclasses import asdict, dataclass, field


# ---------------------------------------------------------------- config

PERMISSIVE_LICENSES = {
    "mit", "apache-2.0", "bsd-3-clause", "bsd-2-clause", "isc",
    "unlicense", "cc0-1.0", "psf-2.0", "python-2.0", "artistic-2.0",
    "zlib", "wtfpl",
}

GENERATED_MARKERS = (
    "auto-generated", "autogenerated", "do not edit", "do not modify",
    "generated by", "@generated", "this file is generated",
)

SECRET_PATTERNS = [
    ("private_key", re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----")),
    ("aws_key", re.compile(r"AKIA[0-9A-Z]{16}")),
    ("github_token", re.compile(r"gh[pousr]_[A-Za-z0-9]{20,}")),
    ("generic_secret_assign", re.compile(
        r"(?i)\b(api[_-]?key|secret|passwd|password|token)\b\s*[:=]\s*['\"][^'\"]{4,}['\"]")),
    ("aws_secret_assign", re.compile(r"(?i)aws_secret_access_key\s*=\s*['\"][^'\"]+['\"]")),
]

PATH_FINGERPRINTS = ("humaneval", "mbpp", "evalplus", "apps_benchmark")


@dataclass
class PipelineConfig:
    max_files: int = 10000
    languages: tuple = ("python",)
    min_bytes: int = 100
    max_bytes: int = 1_000_000
    allowed_licenses: tuple = tuple(sorted(PERMISSIVE_LICENSES))
    drop_unparseable: bool = True
    min_alpha_frac: float = 0.25
    max_mean_line_len: float = 500.0
    max_line_len: int = 5000
    near_dup_jaccard: float = 0.7
    near_dup_max_shingles: int = 1500
    near_dup_max_df: int = 500
    train_frac: float = 0.90
    val_frac: float = 0.05
    # test_frac is implied: 1 - train - val
    scan_secrets: bool = True
    drop_on_secret: bool = True

    def fingerprint(self) -> str:
        d = asdict(self)
        d["languages"] = list(d["languages"])
        d["allowed_licenses"] = list(d["allowed_licenses"])
        return hashlib.sha256(
            json.dumps(d, sort_keys=True).encode()).hexdigest()[:16]


# ---------------------------------------------------------------- records

def new_record(idx: int, content: str, path: str = "", repo: str = "",
               language: str = "", license: str = "", source: str = "",
               source_rev: str = "") -> dict:
    raw = content.encode("utf-8", errors="replace")
    return {
        "id": f"doc-{idx:06d}",
        "content": content,
        "path": path, "repo": repo, "language": language.lower(),
        "license": (license or "").lower(),
        "source": source, "source_rev": source_rev,
        "sha256": hashlib.sha256(raw).hexdigest(),
        "bytes": len(raw),
        "excluded": False, "exclusion_reason": "",
        "secret_hits": [],
        "split": "",
    }


# ---------------------------------------------------------------- stage 1: pre-filters

def is_binary(content: str) -> bool:
    if "\x00" in content:
        return True
    sample = content[:8000]
    if not sample:
        return False
    nontext = sum(1 for c in sample if ord(c) < 9 or 13 < ord(c) < 32 and ord(c) != 27)
    return (nontext / len(sample)) > 0.30


def looks_generated(content: str) -> bool:
    head = content[:2000].lower()
    return any(m in head for m in GENERATED_MARKERS)


def line_stats(content: str):
    lines = content.split("\n")
    n = len(lines) or 1
    lens = [len(l) for l in lines]
    return sum(lens) / n, max(lens) if lens else 0


def looks_minified(content: str, cfg: PipelineConfig) -> bool:
    mean_len, max_len = line_stats(content)
    return mean_len > cfg.max_mean_line_len or max_len > cfg.max_line_len


def prefilter(rec: dict, cfg: PipelineConfig) -> str:
    """Return exclusion reason or '' if the record passes."""
    if rec["language"] not in cfg.languages:
        return "language"
    if not rec["content"] or not rec["content"].strip():
        return "empty"
    if rec["bytes"] < cfg.min_bytes:
        return "too_small"
    if rec["bytes"] > cfg.max_bytes:
        return "too_large"
    if is_binary(rec["content"]):
        return "binary"
    if looks_generated(rec["content"]):
        return "generated"
    if looks_minified(rec["content"], cfg):
        return "minified"
    return ""


# ---------------------------------------------------------------- stage 2: license

def license_ok(rec: dict, cfg: PipelineConfig) -> bool:
    return rec["license"] in cfg.allowed_licenses


# ---------------------------------------------------------------- stage 3: quality

def alpha_frac(content: str) -> float:
    if not content:
        return 0.0
    letters = sum(1 for c in content if c.isalpha())
    return letters / len(content)


def quality_check(rec: dict, cfg: PipelineConfig) -> str:
    if cfg.drop_unparseable and rec["language"] == "python":
        try:
            ast.parse(rec["content"])
        except (SyntaxError, ValueError):
            return "unparseable"
    if alpha_frac(rec["content"]) < cfg.min_alpha_frac:
        return "low_alpha_frac"
    return ""


# ---------------------------------------------------------------- stage 4: secrets

def scan_secrets(rec: dict) -> list:
    hits = []
    for name, pat in SECRET_PATTERNS:
        if pat.search(rec["content"]):
            hits.append(name)
    return hits


# ---------------------------------------------------------------- stage 5: exact dedup

def exact_dedup(records: list, stats: dict) -> list:
    seen = {}
    kept = []
    for rec in records:
        h = rec["sha256"]
        if h in seen:
            rec["excluded"] = True
            rec["exclusion_reason"] = f"exact_dup_of:{seen[h]}"
            stats["exact_dups"] += 1
        else:
            seen[h] = rec["id"]
            kept.append(rec)
    stats["exact_unique"] = len(seen)
    return kept


# ---------------------------------------------------------------- stage 6: near-dup
# Inverted-index candidate generation + exact Jaccard verification.
# Documented, scalable: O(total shingles) index build, exact Jaccard only
# on candidate pairs that share enough shingles.

_WORD = re.compile(r"[A-Za-z_][A-Za-z0-9_]*|[0-9]+")


def shingles(content: str, max_n: int) -> set:
    toks = _WORD.findall(content.lower())[: max_n * 2]
    grams = set()
    for i in range(len(toks) - 4):
        grams.add(" ".join(toks[i:i + 5]))
        if len(grams) >= max_n:
            break
    return grams


def jaccard(a: set, b: set) -> float:
    if not a or not b:
        return 0.0
    inter = len(a & b)
    return inter / (len(a) + len(b) - inter)


def near_dedup(records: list, cfg: PipelineConfig, stats: dict) -> list:
    # Build inverted index: shingle -> doc ids (skip overly common shingles)
    doc_shingles = {}
    df = defaultdict(int)
    for rec in records:
        s = shingles(rec["content"], cfg.near_dup_max_shingles)
        doc_shingles[rec["id"]] = s
        for g in s:
            df[g] += 1
    index = defaultdict(list)
    for rec in records:
        for g in doc_shingles[rec["id"]]:
            if df[g] <= cfg.near_dup_max_df:
                index[g].append(rec["id"])

    # Candidate pairs via shared-shingle counts (deterministic order)
    pair_counts = defaultdict(int)
    for g in sorted(index):
        ids = sorted(index[g])
        # cap pairwise work per shingle to avoid pathological blowup
        if len(ids) > 200:
            continue
        for i in range(len(ids)):
            for j in range(i + 1, len(ids)):
                pair_counts[(ids[i], ids[j])] += 1

    id2rec = {r["id"]: r for r in records}
    # A pair is a near-dup candidate if shared shingles suggest Jaccard >= threshold.
    # Required shared >= threshold * max(|A|,|B|); use min size as cheap lower bound.
    dup_of = {}
    for (a, b) in sorted(pair_counts):
        sa, sb = doc_shingles[a], doc_shingles[b]
        need = cfg.near_dup_jaccard * max(len(sa), len(sb))
        if pair_counts[(a, b)] < need * 0.5:  # cheap pre-filter
            continue
        if jaccard(sa, sb) >= cfg.near_dup_jaccard:
            # keep the earlier record (deterministic: lower id)
            dup_of[b] = a
            stats["near_dup_pairs"] += 1

    kept = []
    for rec in records:
        if rec["id"] in dup_of:
            rec["excluded"] = True
            rec["exclusion_reason"] = f"near_dup_of:{dup_of[rec['id']]}"
            stats["near_dups"] += 1
        else:
            kept.append(rec)
    return kept


# ---------------------------------------------------------------- stage 8: split (hash-based, dup-proof)

def assign_split(rec: dict, cfg: PipelineConfig) -> str:
    h = int(hashlib.sha256(rec["sha256"].encode()).hexdigest(), 16) % 10000
    train_cut = int(cfg.train_frac * 10000)
    val_cut = train_cut + int(cfg.val_frac * 10000)
    if h < train_cut:
        return "train"
    if h < val_cut:
        return "val"
    return "test"


# ---------------------------------------------------------------- pipeline driver

def run_pipeline(records: list, cfg: PipelineConfig, decontam=None) -> tuple:
    t0 = time.time()
    stats = defaultdict(int)
    stats["discovered"] = len(records)

    # stage 1: prefilter
    live = []
    for rec in records:
        reason = prefilter(rec, cfg)
        if reason:
            rec["excluded"] = True
            rec["exclusion_reason"] = reason
            stats[f"excluded_{reason}"] += 1
        else:
            live.append(rec)
    stats["after_prefilter"] = len(live)

    # stage 2: license
    live2 = []
    for rec in live:
        if not license_ok(rec, cfg):
            rec["excluded"] = True
            rec["exclusion_reason"] = f"license:{rec['license'] or 'unknown'}"
            stats["excluded_license"] += 1
        else:
            live2.append(rec)
    stats["after_license"] = len(live2)

    # stage 3: quality
    live3 = []
    for rec in live2:
        reason = quality_check(rec, cfg)
        if reason:
            rec["excluded"] = True
            rec["exclusion_reason"] = reason
            stats[f"excluded_{reason}"] += 1
        else:
            live3.append(rec)
    stats["after_quality"] = len(live3)

    # stage 4: secrets
    if cfg.scan_secrets:
        for rec in live3:
            hits = scan_secrets(rec)
            if hits:
                rec["secret_hits"] = hits
                stats["secret_flagged"] += 1
                if cfg.drop_on_secret:
                    rec["excluded"] = True
                    rec["exclusion_reason"] = "possible_secret:" + ",".join(hits)
                    stats["excluded_secret"] += 1
        live3 = [r for r in live3 if not r["excluded"]]
    stats["after_secrets"] = len(live3)

    # stage 5+6: dedup
    live4 = exact_dedup(live3, stats)
    stats["after_exact_dedup"] = len(live4)
    live5 = near_dedup(live4, cfg, stats)
    stats["after_near_dedup"] = len(live5)

    # stage 7: decontamination (optional hook)
    if decontam is not None:
        live5 = decontam.apply(live5, stats)
        stats["after_decontam"] = len([r for r in live5 if not r["excluded"]])
        live5 = [r for r in live5 if not r["excluded"]]

    # stage 8: split
    for rec in live5:
        rec["split"] = assign_split(rec, cfg)
    stats["split_train"] = sum(1 for r in live5 if r["split"] == "train")
    stats["split_val"] = sum(1 for r in live5 if r["split"] == "val")
    stats["split_test"] = sum(1 for r in live5 if r["split"] == "test")
    stats["retained"] = len(live5)
    stats["bytes_retained"] = sum(r["bytes"] for r in live5)
    stats["elapsed_s"] = round(time.time() - t0, 2)
    stats["config_fingerprint"] = cfg.fingerprint()
    return records, live5, dict(stats)


def write_manifest(all_records: list, path: str, provenance: dict):
    with open(path, "w") as f:
        for rec in all_records:
            entry = {k: v for k, v in rec.items() if k != "content"}
            entry["provenance"] = provenance
            f.write(json.dumps(entry, sort_keys=True) + "\n")


def write_corpus(kept: list, path: str):
    with open(path, "w") as f:
        for rec in kept:
            f.write(json.dumps({
                "id": rec["id"], "sha256": rec["sha256"],
                "path": rec["path"], "repo": rec["repo"],
                "language": rec["language"], "license": rec["license"],
                "split": rec["split"], "content": rec["content"],
            }, sort_keys=True) + "\n")
